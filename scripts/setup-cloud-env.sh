#!/bin/bash
# ---------------------------------------------------------------------------
# scripts/setup-cloud-env.sh
#
# Claude Code on the web の「セットアップスクリプト」に貼る内容。
# 環境ダイアログ（claude.ai/code の環境セレクタ）に設定するが、内容はここで版管理する。
# ずれたら気づけるよう、CI が scripts/setup-cloud-env.sh.sha256 と突き合わせる。
#
# 現在このスクリプトは何もしない。意図的である。
#
#   セットアップスクリプトは5分以内に終える必要があり（超えると環境キャッシュが
#   作られず、毎セッション走る）、短いほどよい。
#   P0 の時点で、クラウドセッションのプリインストールに足すものが無い:
#
#     - Node.js 22 / npm            … プリインストール
#     - PostgreSQL 16               … プリインストール（起動は install_pkgs.sh）
#     - Playwright のブラウザ       … /opt/pw-browsers に chromium-1194 が入っており、
#                                     PLAYWRIGHT_BROWSERS_PATH が設定済み。
#                                     @playwright/test を 1.56.1 に完全固定してあり、
#                                     1.56系が要求するのがこの 1194 なので install は不要。
#                                     バージョンを上げると要求リビジョンが変わり
#                                     （1.57→1200 / 1.58→1208 / 1.59→1217 /
#                                       1.60→1223 / 1.61→1228 / 1.62→1234）、
#                                     ここでのダウンロードが必要になって5分に当たる。
#                                     対応関係は tests/unit/playwright-pin.test.ts が検査する
#     - docker / git / gh / jq / rg … プリインストール
#
# 足すものができたら、ここに書いて sha256 を更新し、環境ダイアログにも貼り直す。
# 重要でないコマンドには `|| true` を付ける（終了コード0でないとセッションが起動しない）。
#
# 実行条件（公式の制約）:
#   - root で走る（Ubuntu 24.04）
#   - 終了コード 0 が必須
#   - 5分以内
#   - キャッシュはファイルシステムのスナップショット。
#     ここで起動したプロセスは残らない（Postgres の起動は install_pkgs.sh 側）
# ---------------------------------------------------------------------------
set -u

echo "[setup-cloud-env] 追加のセットアップはありません（プリインストールで足ります）"
exit 0
